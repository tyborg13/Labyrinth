	if [[ "${EXPORT_MACOS}" -eq 1 && ! -d "$(macos_output_path)" ]]; then
		fail "Missing macOS export at $(macos_output_path). Run without --upload-only first."
	fi
	if [[ "${EXPORT_WINDOWS}" -eq 1 && ! -f "$(windows_output_path)" ]]; then
		fail "Missing Windows export at $(windows_output_path). Run without --upload-only first."
	fi
