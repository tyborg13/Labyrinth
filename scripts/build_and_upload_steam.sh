staging_output_path() {
	local platform="$1"
	case "${platform}" in
		macos)
			printf '%s/macos/%s' "${EXPORT_STAGING_ROOT}" "${STEAM_MACOS_APP_NAME}"
			;;
		windows)
			printf '%s/windows/%s' "${EXPORT_STAGING_ROOT}" "${STEAM_WINDOWS_EXECUTABLE_NAME}"
			;;
		linux)
			printf '%s/linux/%s' "${EXPORT_STAGING_ROOT}" "${STEAM_LINUX_EXECUTABLE_NAME}"
			;;
		*)
			fail "Unsupported export platform '${platform}'."
			;;
	esac
}

export_platform() {
	local platform="$1"
	local preset_name staging_path staging_parent_dir
	case "${platform}" in
		macos)
			preset_name="Steam macOS"
			;;
		windows)
			preset_name="Steam Windows"
			;;
		linux)
			preset_name="Steam Linux"
			;;
		*)
			fail "Unsupported export platform '${platform}'."
			;;
	esac
	staging_path="$(staging_output_path "${platform}")"
	staging_parent_dir="$(dirname "${staging_path}")"

	log "Exporting ${platform} build with preset '${preset_name}'."
	rm -rf "${staging_parent_dir}"
	ensure_dir "${staging_parent_dir}"
	(
		cd "${EXPORT_PROJECT_ROOT}"
		"${GODOT_BINARY}" --headless --path . --export-release "${preset_name}" "${staging_path}"
	)
	if [[ "${platform}" == "linux" && -f "${staging_path}" ]]; then
		chmod +x "${staging_path}"
	fi
}

sync_staged_platform_output() {
	local platform="$1"
	local output_path parent_dir staging_path staging_parent_dir
	case "${platform}" in
		macos)
			output_path="$(macos_output_path)"
			;;
		windows)
			output_path="$(windows_output_path)"
			;;
		linux)
			output_path="$(linux_output_path)"
			;;
		*)
			fail "Unsupported export platform '${platform}'."
			;;
	esac
	parent_dir="$(dirname "${output_path}")"
	staging_path="$(staging_output_path "${platform}")"
	staging_parent_dir="$(dirname "${staging_path}")"
	rm -rf "${parent_dir}"
	ensure_dir "${parent_dir}"
	cp -R "${staging_parent_dir}/." "${parent_dir}/"
	if [[ "${platform}" == "linux" && -f "${output_path}" ]]; then
		chmod +x "${output_path}"
	fi
}

