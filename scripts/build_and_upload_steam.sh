#!/usr/bin/env bash
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEFAULT_CONFIG_PATH="${PROJECT_ROOT}/steam/steam_build_config.env"
DEFAULT_GODOT_BINARY="/Applications/Godot.app/Contents/MacOS/Godot"
DEFAULT_STEAMCMD_URL="https://steamcdn-a.akamaihd.net/client/installer/steamcmd_osx.tar.gz"
STEAMCMD_DIR="${PROJECT_ROOT}/.steam/sdk/tools/ContentBuilder/builder_osx"
STEAMCMD_SH="${STEAMCMD_DIR}/steamcmd.sh"
HOST_ARCH="$(uname -m)"
BUILD_ROOT="${PROJECT_ROOT}/build/steam"
CONTENT_ROOT="${BUILD_ROOT}/content"
STEAMPIPE_ROOT="${BUILD_ROOT}/steampipe"
