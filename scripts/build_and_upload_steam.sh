write_depot_script() {
	local target="$1"
	local platform="$2"
	local depot_id="$3"
	local depot_script_path="$4"
	local content_root local_path depot_path

	case "${platform}" in
		macos)
			content_root="$(dirname "$(macos_output_path)")"
			local_path="*"
			depot_path="."
			;;
		windows)
			content_root="$(dirname "$(windows_output_path)")"
			local_path="*"
			depot_path="."
			;;
		linux)
			content_root="$(dirname "$(linux_output_path)")"
			local_path="*"
			depot_path="."
			;;
		*)
			fail "Unknown platform '${platform}' while writing depot script."
			;;
	esac

	cat > "${depot_script_path}" <<EOF
"DepotBuild"
{
	"DepotID" "$(vdf_escape "${depot_id}")"
	"ContentRoot" "$(vdf_escape "${content_root}")"
	"FileMapping"
	{
		"LocalPath" "${local_path}"
		"DepotPath" "${depot_path}"
		"recursive" "1"
	}
}
EOF
}

write_app_build_script() {
	local target="$1"
	local branch app_id build_desc app_script_path output_dir depot_script_path
	local set_live_line=""
	local depots_block=""
	local platform depot_id

	app_id="$(target_app_id "${target}")"
	branch="$(target_branch "${target}")"
	build_desc="$(build_description) | ${target}"
	app_script_path="${STEAMPIPE_SCRIPT_ROOT}/app_build_${target}.vdf"
	output_dir="${STEAMPIPE_OUTPUT_ROOT}/${target}"

	is_positive_int "${app_id}" || fail "Missing ${target} App ID in ${CONFIG_PATH}."

	ensure_dir "${STEAMPIPE_SCRIPT_ROOT}"
	ensure_dir "${output_dir}"

	for platform in macos windows linux; do
		if ! platform_enabled "${platform}"; then
			continue
		fi
		depot_id="$(target_depot_id "${target}" "${platform}")"
		if ! is_positive_int "${depot_id}"; then
			log "Skipping ${target}/${platform}: no depot ID configured in ${CONFIG_PATH}."
			continue
		fi
		depot_script_path="${STEAMPIPE_SCRIPT_ROOT}/depot_build_${target}_${platform}.vdf"
		write_depot_script "${target}" "${platform}" "${depot_id}" "${depot_script_path}"
		depots_block="${depots_block}
		\"${depot_id}\" \"$(vdf_escape "${depot_script_path}")\""
	done

	[[ -n "${depots_block}" ]] || fail "No depot IDs configured for target '${target}' across the selected platforms."

	if [[ -n "${branch}" && "${branch}" != "default" ]]; then
		set_live_line=$'\t'"\"SetLive\" \"$(vdf_escape "${branch}")\""$'\n'
	fi

	cat > "${app_script_path}" <<EOF
"AppBuild"
{
	"AppID" "$(vdf_escape "${app_id}")"
	"Desc" "$(vdf_escape "${build_desc}")"
	"BuildOutput" "$(vdf_escape "${output_dir}")"
	"Preview" "${PREVIEW_BUILD}"
${set_live_line}	"ContentRoot" "$(vdf_escape "${CONTENT_ROOT}")"
	"Depots"
	{
${depots_block}
	}
}
EOF

	printf '%s' "${app_script_path}"
}

run_steamcmd_upload() {
	local target="$1"
	local branch app_build_path
	app_build_path="$(write_app_build_script "${target}")"
	branch="$(target_branch "${target}")"

	if [[ "${DRY_RUN}" -eq 1 ]]; then
		log "Dry run: generated ${app_build_path}"
		if [[ -n "${branch}" && "${branch}" != "default" ]]; then
			log "Dry run: this build would auto-set branch '${branch}' live."
		else
			log "Dry run: this build would require a manual Set Live click for the default branch."
		fi
		return
	fi

	[[ -n "${STEAM_BUILDER_USERNAME}" ]] || fail "Set STEAM_BUILDER_USERNAME in ${CONFIG_PATH} or pass --steam-username."

	log "Uploading ${target} build through SteamCMD."
	if [[ -n "${STEAM_GUARD_CODE:-}" ]]; then
		run_steamcmd +set_steam_guard_code "${STEAM_GUARD_CODE}" +login "${STEAM_BUILDER_USERNAME}" +run_app_build "${app_build_path}" +quit
	else
		run_steamcmd +login "${STEAM_BUILDER_USERNAME}" +run_app_build "${app_build_path}" +quit
	fi

	if [[ -n "${branch}" && "${branch}" != "default" ]]; then
		log "Uploaded ${target} build and requested SetLive for beta branch '${branch}'."
	else
		log "Uploaded ${target} build. Steam requires a manual Set Live for the default branch:"
		log "  $(target_builds_url "${target}")"
	fi
}

main() {
	parse_args "$@"
	load_config
	validate_environment
	select_targets
	select_platforms

	log "Selected targets: ${TARGETS_CSV}"
	log "Selected platforms: $(platform_list_csv)"
	if [[ "${TARGET_MAIN}" -eq 1 ]]; then
		validate_unique_target_depots main
	fi
	if [[ "${TARGET_PLAYTEST}" -eq 1 ]]; then
		validate_unique_target_depots playtest
	fi

	if [[ "${MODE}" != "upload-only" ]]; then
		ensure_godot_templates
		prepare_export_project
		rm -rf "${CONTENT_ROOT}" "${EXPORT_STAGING_ROOT}"
		ensure_dir "${CONTENT_ROOT}"
		if [[ "${EXPORT_MACOS}" -eq 1 ]]; then
			export_platform macos
		fi
		if [[ "${EXPORT_WINDOWS}" -eq 1 ]]; then
			export_platform windows
		fi
		if [[ "${EXPORT_LINUX}" -eq 1 ]]; then
			export_platform linux
		fi
		if [[ "${EXPORT_MACOS}" -eq 1 ]]; then
			sync_staged_platform_output macos
		fi
		if [[ "${EXPORT_WINDOWS}" -eq 1 ]]; then
			sync_staged_platform_output windows
		fi
		if [[ "${EXPORT_LINUX}" -eq 1 ]]; then
			sync_staged_platform_output linux
		fi
		ensure_export_outputs_exist
		validate_exported_content
	fi

	if [[ "${MODE}" != "export-only" ]]; then
		ensure_export_outputs_exist
		validate_exported_content
		if [[ "${DRY_RUN}" -eq 0 ]]; then
			ensure_steamcmd
		fi
		if [[ "${TARGET_MAIN}" -eq 1 ]]; then
			run_steamcmd_upload main
		fi
		if [[ "${TARGET_PLAYTEST}" -eq 1 ]]; then
			run_steamcmd_upload playtest
		fi
	fi

	log "Done."
}

main "$@"
