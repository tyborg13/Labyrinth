"""Generate feedback-3 data from director rules and the immutable mq-17 source.

This is the only writer of design.json. Generated arrays are never hand-tuned.
"""
import json
import math
from pathlib import Path
import numpy as np
from spec.art_identity.maquettes.blender.curate_delivery import write
from spec.art_identity.maquettes.raster import project
from ..recipe import compile_spec as baseline_spec
from .pose import rotation

FOLDER = Path(__file__).resolve().parent
POSE_RULES = {'far_knee_degrees': 10, 'near_knee_degrees': 22, 'pelvis_down_near_degrees': 4, 'forward_lean_degrees': 14, 'chest_yaw_toward_viewer_degrees': 6, 'head_down_degrees': 15, 'ankle_span_over_shoulders': 1.5, 'near_step_over_L': 0.18, 'fist_height_over_H': 0.56, 'fist_forward_over_L': 0.1, 'fist_outward_over_L': 0.36, 'staff_from_vertical_degrees': 4, 'staff_forward_degrees': 4, 'far_elbow_outward_degrees': 40, 'near_upper_out_degrees': 20, 'near_elbow_degrees': 45, 'near_knuckle_degrees': 45, 'near_wrist_ahead_over_L': 0.15}


def counter_roll(baseline,p):
    """Keep exact 3D level; feedback 3 accepts at most 15px screen error."""
    old=np.subtract(baseline['joints']['shoulder_near'],baseline['joints']['shoulder_far'])
    pitch,yaw=p['forward_lean_degrees'],p['chest_yaw_toward_viewer_degrees']
    exact=math.degrees(math.asin(math.tan(math.radians(pitch))*old[0]/old[1]))
    delta=rotation([0,0,1],yaw)@rotation([0,1,0],pitch)@rotation([1,0,0],exact)@old
    centre=(np.asarray(baseline['joints']['shoulder_near'])+baseline['joints']['shoulder_far'])/2
    near,far=(project(baseline,centre+sign*delta/2,'front',1024) for sign in (1,-1))
    error=float(abs((near[1]-far[1])-.15*abs(near[0]-far[0])))
    return {'chest_roll_degrees':exact,'exact_level_roll_degrees':exact,
        'hip_centre_x_over_L':0.,'shoulder_z_difference_over_H':float(delta[2]/baseline['mq17']['height_m']),
        'shoulder_projection_error_px':error,'level_tolerance_over_H':.005,
        'shoulder_rule_limit_px':15.,'standard_shoulder_rule_limit_px':10.,
        'shoulder_exception_used':error>10.,'minimum_staff_clearance_over_L':.03,
        'authority':'feedback 3: exact level shoulders, figure-specific 15px allowance; staff 4 degrees accepted'}


def tabard_hem(baseline):
    piece = next(p for p in baseline['pieces'] if p['id']=='front_tabard')
    nr,nc = baseline['volume_layout']['tabard_grid'];count=nr*nc
    vertices = np.asarray(piece['vertices']);base=((vertices[:count]+vertices[count:])/2).reshape(nr,nc,3)[-1,:,2]/baseline['mq17']['height_m']
    columns=np.arange(nc);depths=[.04,.06,.03,.05,.04];centres=[2,7,12,17,22]
    removed=sum(depth*np.maximum(0,1-abs(columns-centre)/2.5) for centre,depth in zip(centres,depths))
    return {'points':5,'point_columns':centres,'point_depths_over_H':depths,
            'tent_half_width_columns':2.5,'base_hem_z_over_H':base.tolist(),
            'hem_z_over_H':(base-removed).tolist()}


def generate():
    baseline=baseline_spec();data={'pose':dict(POSE_RULES)}
    data['authority']='mq-19 feedback 3, director final rules; generated by generate_design.py'
    data['pose_resolution']=counter_roll(baseline,data['pose'])
    data['tabard']=tabard_hem(baseline)
    from .cloak_generator import generate as cloak
    from .recipe import pose_spec
    data['cloak']=cloak(pose_spec(data))
    return data


if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    generated=generate()
    if args.check:
        if generated!=json.loads((FOLDER/'design.json').read_text()):raise ValueError('Generated design differs; rerun generator')
    else:write(FOLDER/'design.json',generated)
    print('MQ19_GENERATED_DESIGN: PASS')
