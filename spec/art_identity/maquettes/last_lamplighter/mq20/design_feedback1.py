"""Numeric transcription of director mq-20_feedback_1.md.

Knuckle X determines azimuth on the outside of the top ring. Each finger
sweeps 270 degrees about that bar at the specified bend radius, then meets
the inherited ellipsoid palm. The thumb follows the outside of the index
finger's middle 90-degree arc. Ten-degree sampling only tessellates curves.
"""
import json
import math
from pathlib import Path
from .recipe import retained_head
from .pose import solve
from ..recipe import compile_spec as mq18

FOLDER = Path(__file__).resolve().parent


def generate():
    baseline = mq18()
    pose = dict(baseline['pose'], **json.loads((FOLDER/'directives.json').read_text())['pose'])
    dimensions=dict(baseline['dimensions'], **json.loads((FOLDER/'directives.json').read_text())['dimensions'])
    joints,_=solve(baseline['source_calipers'],pose,baseline['mq18']['height_m'],
                   baseline['mq18']['leg_length_m'],baseline['mq18']['source_unit_m_per_px'],dimensions)
    head = retained_head(baseline, joints, pose)
    height = max(v[2] for p in head if p['part']=='hood' for v in p['vertices'])
    c=baseline['source_calipers'];u=baseline['mq18']['source_unit_m_per_px']
    palm=[c['hand_depth_px']*u/(2*height),baseline['dimensions']['gauntlet_width_over_H']/2,c['hand_length_px']*u/(2*height)]
    radius,bend=.018,.012
    fingers=[];radials=[]
    for i in range(4):
        azimuth=math.asin((i-1.5)*.012/(radius+bend))
        radial=[math.sin(azimuth),0,math.cos(azimuth)];radials.append(radial)
        path=[]
        for degrees in range(0,271,10):
            a=math.radians(degrees)
            path.append([(radius+bend*math.cos(a))*radial[0],bend*math.sin(a),(radius+bend*math.cos(a))*radial[2]])
        tip=path[-1];scale=math.sqrt(sum((v/r)**2 for v,r in zip(tip,palm)))
        path.append([v/scale for v in tip]);fingers.append(path)
    # Equal-radius thumb and finger tubes touch at one full tube diameter.
    thickness=baseline['dimensions']['claw_thickness_over_H'];radial=radials[0];thumb=[]
    for degrees,point in zip(range(90,181,10),fingers[0][9:19]):
        a=math.radians(degrees);normal=[math.cos(a)*radial[0],math.sin(a),math.cos(a)*radial[2]]
        thumb.append([v+thickness*n for v,n in zip(point,normal)])
    widths=[.03,.04,.02,.05,.03,.04,.02,.05,.03,.04]
    lengths=[.18,.12,.07,.10,.05,.08,.06,.11,.14,.17]
    profile=[[0,0],[1,0],[.85,.70],[.65,1],[.45,.85],[.20,.60]]
    strands=[{'start_s':(i+.5)/10-width/2,'width_over_H':width,'length_over_H':length,
              'profile':[[1-x if i%2 else x,y] for x,y in profile]}
             for i,(width,length) in enumerate(zip(widths,lengths))]
    octagon=[[(.5 if i%2==0 else .38)*math.cos(math.radians(45*i)),
              (.5 if i%2==0 else .38)*math.sin(math.radians(45*i))] for i in range(8)]
    holes=[{'s':s,'t':t,'diameter_over_H':d,'profile':octagon}
           for s,t,d in [(.18,.62,.025),(.41,.48,.020),(.66,.70,.030),(.83,.55,.022)]]
    notches={side:[{'t':t,'depth_over_H':depth,'profile':[[0,-.5],[1,0],[0,.5]]} for t in locations]
             for side,depth,locations in [('near',.025,[.35,.60,.80]),('far',.020,[.45,.72])]}
    result={
        'authority':'Director mq-20_feedback_1.md; generated by mq20/design_feedback1.py.',
        'TODO_DESIGN_pauldron_surface':{'corner_radius_over_H':.03,'convexity_over_H':.015,
            'rim_width_over_H':.012,'rim_proud_over_H':.006,'cross_width_over_H':.022,'rivet_radius_over_H':.004,
            'rivets_yz_over_H':[[y,z] for y in [-.08,.08] for z in [-.065,.065]]+[[-.094,0],[.094,0],[0,-.079],[0,.079]]},
        'TODO_DESIGN_pauldron_placement':{'near_xy_over_H':[-.01,.04],'far_xy_over_H':[-.01,-.04],'hood_top_gap_over_H':.015},
        'TODO_DESIGN_lantern_grip':{'ring_radius_over_H':radius,'ring_plane':'xz','finger_paths_over_H':fingers,'thumb_path_over_H':thumb},
        'TODO_DESIGN_robe_layout':{'strands':strands,'holes':holes,'notches':notches},
        'TODO_DESIGN_lantern_leg_clearance_resolution':{'required_minimum_over_H':.04,'fist_outward_start_over_L':.30,
            'fist_outward_step_over_L':.02,'fist_outward_max_over_L':.44,
            'rule':'Use the first passing step; all other pose values fixed; stop if 0.44 fails.'}}
    return json.loads(json.dumps(result),parse_float=lambda v:round(float(v),12))


if __name__=='__main__':
    (FOLDER/'design_details.json').write_text(json.dumps(generate(),indent=2)+'\n')
