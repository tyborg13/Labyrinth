#!/usr/bin/env python3
"""Exclude output-only folders from Godot imports without hiding probe inputs.

Run before suites/probes, and again after creating new output folders. Only add
markers to Git when the folder already contains tracked artifacts. No artifacts
or existing markers are removed; a newly referenced ignored folder is an error.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]
SOURCE_SUFFIXES = {".gd", ".py", ".sh", ".json", ".tscn", ".tres", ".godot"}
OUTPUT_REFERENCE = re.compile(r"res://" r"output/([^\s\"'`<>\\]*)")
# Audited sinks: these constants feed mkdir, save_png or FileAccess.WRITE only.
# Match source AND literal; a reference added elsewhere stays importable.
WRITE_ONLY_REFERENCES = {
    ("tests/en03_enemies_probe.gd", "en03-enemies"),
    ("tests/en06_enemies_probe.gd", "en06-enemies"),
    ("tests/health_ghost_probe.gd", "feel-02/health_ghost"),
    ("tests/relic_u2_probe.gd", "relic-u2-probe"),
    ("tests/section_map_flow_probe.gd", "fix-01"),
    ("tests/section_map_flow_probe.gd", "fix-01/pause-proof-contract.json"),
    ("tests/suites/combat_feel_suite.gd", "feel-01"),
}
MARKER = "# Generated by tools/output_gdignore.py: no res:// consumers in this subtree.\n"


def git_files(root: Path, *, include_untracked: bool = False) -> list[str]:
    command = ["git", "ls-files", "-z", "--cached"]
    if include_untracked:
        command += ["--others", "--exclude-standard"]
    result = subprocess.run(command, cwd=root, check=True, capture_output=True)
    return sorted(set(result.stdout.decode().rstrip("\0").split("\0")) - {""})


def scan_references(root: Path, files: list[str]) -> dict[str, list[str]]:
    references: dict[str, list[str]] = {}
    for name in files:
        source = Path(name)
        # output contains proposals with hypothetical art paths, not live inputs.
        # Keep whole referenced subtrees so relative cutout dependencies survive.
        if source.parts[0] == "output" or source.suffix not in SOURCE_SUFFIXES:
            continue
        path = root / source
        if not path.is_file() or path.is_symlink():
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for match in OUTPUT_REFERENCE.finditer(line):
                relative = match[1]
                if (name, relative) in WRITE_ONLY_REFERENCES:
                    continue
                # Dynamic top-level paths cannot safely exclude any folder.
                folder = relative.split("/", 1)[0]
                if not folder or any(token in folder for token in ("%", "{", "}", "$")):
                    raise ValueError(f"Dynamic output root needs review: {name}:{number}")
                references.setdefault(folder, []).append(f"{name}:{number}: {match[0]}")
    return references


def reconcile(root: Path, *, check: bool = False) -> int:
    references = scan_references(root, git_files(root, include_untracked=True))
    tracked = {Path(name).parts[1] for name in git_files(root)
               if name.startswith("output/") and len(Path(name).parts) > 2}
    output = root / "output"
    problems: list[str] = []
    for folder, sources in sorted(references.items()):
        print(f"KEEP output/{folder}: {'; '.join(sources)}")
    if not output.exists():
        return 0
    folders = sorted(path for path in output.iterdir() if path.is_dir())
    # Validate before writing anything. Never follow a symlink outside the tree.
    for folder in folders:
        if folder.is_symlink():
            problems.append(f"Symlink needs review: {folder.relative_to(root)}")
        elif folder.name in references:
            for marker in folder.rglob(".gdignore"):
                problems.append(f"Referenced subtree is ignored: {marker.relative_to(root)}")
    if (output / ".gdignore").exists():
        problems.append("output/.gdignore would hide all resource consumers")
    if problems:
        for problem in problems:
            print(f"ERROR {problem}")
        return 1
    for folder in folders:
        if folder.name in references:
            continue
        marker = folder / ".gdignore"
        if marker.exists():
            continue
        scope = "tracked folder" if folder.name in tracked else "local folder; do not commit"
        print(f"{'MISSING' if check else 'WRITE'} {marker.relative_to(root)} ({scope})")
        if check:
            problems.append(str(marker))
        else:
            marker.write_text(MARKER, encoding="utf-8")
    print(f"OUTPUT GDIGNORE: {'FAIL' if problems else 'PASS'} "
          f"({len(folders)} folders; {len(references)} referenced roots)")
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report missing/conflicting markers without writing")
    args = parser.parse_args()
    try:
        return reconcile(ROOT, check=args.check)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"OUTPUT GDIGNORE: FAIL ({error})\n")


if __name__ == "__main__":
    raise SystemExit(main())
