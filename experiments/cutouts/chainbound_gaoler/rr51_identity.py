"""rr-51: rr-49's exact submission identity, recorded fresh at the 1.10 board scale.

rr-49 froze 304,685 polygon buffers from the 2bd5ea39a scalar path at the
0.90 board scale and step. Those buffers stay exact (no rig byte changed), but
the production board now presents the Gaoler at a new screen-pixel scale and
step. This freezes the same 8,364 cases at the measured 1.10 production
geometry, generated by rr-49's own frozen 2bd5ea39a adapter (never by the
optimized production path it checks), with an explicit before/after record.

  PYTHONPATH=tools python3 -B experiments/cutouts/chainbound_gaoler/rr51_identity.py freeze --scale S --step T
"""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

from rr44_case import PROJECT, CASE

BEFORE = CASE.parent / 'rr49/fixtures/submission_2bd5ea39a'
BEFORE_MANIFEST_SHA256 = 'de38d3fb2145f0a0b81d249f202bb25305d6218c96a5fe08818d250d932ce7e7'
FIXTURE = CASE.parent / 'rr51/fixtures/submission_scale_1p10'
ORACLE = 'res://' + str((BEFORE / 'legacy_production.gd').relative_to(PROJECT))
# Proof-only runner deadline for the frozen 23.5 ms/pose scalar oracle.
ORACLE_TIMEOUT_SECONDS = 900
PRIOR_ART_SCALE = 0.9
ART_SCALE = 1.1


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def rescaled_cases(scale, step):
    """Same cases and origins; every scaled config moves to the new geometry."""
    cases = json.loads((BEFORE / 'cases.json').read_text())
    configs = []
    for config in cases['configs']:
        config = dict(config)
        if 'scale' in config: config['scale'] = scale
        if config.get('step', 0.0): config['step'] = step
        configs.append(config)
    return dict(cases, configs=configs)


def hashes(cases_path, output, rig=None, task='rr-51', timeout=ORACLE_TIMEOUT_SECONDS):
    arguments = ['--input', str(cases_path), '--output', str(output)] + (['--rig', rig] if rig else [])
    subprocess.run([sys.executable, 'tools/godot_task_runner.py', '--task-id', task, '--timeout', str(timeout),
                    '--stream', '--', 'godot', '--headless', '--path', '.', '--script', 'tests/rr49/submission_hashes.gd',
                    '--', *arguments], cwd=PROJECT, check=True, timeout=timeout + 5)
    return json.loads(Path(output).read_text())


def freeze(scale, step):
    if FIXTURE.exists(): raise ValueError('Never overwrite a frozen identity record')
    if sha(BEFORE / 'manifest.json') != BEFORE_MANIFEST_SHA256: raise ValueError('rr-49 identity record changed')
    FIXTURE.mkdir(parents=True)
    cases = rescaled_cases(scale, step)
    (FIXTURE / 'cases.json').write_text(json.dumps(cases, separators=(',', ':')) + '\n')
    with tempfile.TemporaryDirectory(prefix='rr51-identity-') as folder:
        oracle = hashes(FIXTURE / 'cases.json', Path(folder) / 'oracle.json', ORACLE)
    payload = json.dumps(oracle, separators=(',', ':')).encode()
    (FIXTURE / 'buffers.json.gz').write_bytes(gzip.compress(payload, mtime=0))
    before = json.loads((BEFORE / 'cases.json').read_text())['configs']
    (FIXTURE / '.gdignore').write_text('# Frozen rr-51 identity inputs; Python and the rr-49 hash probe read them by path.\n')
    manifest = {
        'unit': 'rr-51', 'oracle': ORACLE, 'oracle_sha256': sha(BEFORE / 'legacy_production.gd'),
        'oracle_revision': json.loads((BEFORE / 'manifest.json').read_text())['head'],
        'poses': oracle['poses'], 'polygon_buffers': oracle['buffers'],
        'before': {'fixture': str(BEFORE.relative_to(PROJECT)), 'manifest_sha256': BEFORE_MANIFEST_SHA256,
                   'art_scale': PRIOR_ART_SCALE, 'configs': before},
        'after': {'art_scale': ART_SCALE, 'configs': cases['configs'],
                  'geometry': 'tests/gait01/board_geometry.gd at 1920x1080, 100% UI scale, seed 91210, tile (2, 4)'},
        'files': {name: sha(FIXTURE / name) for name in ('.gdignore', 'buffers.json.gz', 'cases.json')}}
    (FIXTURE / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('RR51 IDENTITY RECORD: %d poses; %d buffers; manifest %s' % (oracle['poses'], oracle['buffers'], sha(FIXTURE / 'manifest.json')))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['freeze'])
    parser.add_argument('--scale', type=float, required=True)
    parser.add_argument('--step', type=float, required=True)
    arguments = parser.parse_args()
    freeze(arguments.scale, arguments.step)
