"""Derive the Thrall probe without changing the shared renderer's behaviour.

The shared probe has no rest-source hook. Keep its rendering code verbatim,
with only the layout rest selector, isolated evidence hashes, and absolute
location of its relative helper changed. A regression test checks the result.
"""
from rr24_build import PROJECT

SHARED_PROBE = PROJECT/'tests/rr11/native_capture.gd'
THRALL_PROBE = PROJECT/'experiments/cutouts/arc_thrall/rr24_native_capture.gd'


def source():
    code = SHARED_PROBE.read_text()
    replacements = [
        ('preload("board_scales.gd")','preload("res://tests/rr11/board_scales.gd")'),
        ('Image.load_from_file(directory.path_join("source/" + view + "/processed.png"))',
         'rest_reference(view)'),
        ('"name": entry["part"]["name"], "file": file, "checks": checks,',
         '"name": entry["part"]["name"], "file": file, "checks": checks,\n'
         '\t\t\t\t\t\t"sha256": CaptureStorage.file_hash(path(file)), "checks_sha256": CaptureStorage.file_hash(path(checks)),'),
        ('print("RR11 NATIVE PROBE LOAD: "',
         '_validate_rest_references()\n\t\tprint("RR11 NATIVE PROBE LOAD: "')]
    for old,new in replacements:
        if code.count(old)!=1: raise ValueError('Shared probe changed: '+old)
        code = code.replace(old,new)
    return '# Generated by rr24_capture_source.py; shared rendering code is preserved.\n'+code+'''

func rest_reference(view: String) -> Image:
	var layout: Dictionary = JSON.parse_string(FileAccess.get_file_as_string(directory.path_join("layouts/" + view + ".json")))
	return Image.load_from_file(directory.path_join(str(layout["rest_source"])))

func _validate_rest_references() -> void:
	for view: String in data["view_tracks"]:
		var layout: Dictionary = JSON.parse_string(FileAccess.get_file_as_string(directory.path_join("layouts/" + view + ".json")))
		var selected: Image = rest_reference(view)
		var expected: Image = Image.load_from_file(directory.path_join(str(layout["rest_source"])))
		selected.convert(Image.FORMAT_RGBA8)
		expected.convert(Image.FORMAT_RGBA8)
		if selected.get_data() != expected.get_data(): failures.append(view + ": layout rest reference differs")
		print("RR24 REST REFERENCE " + view.to_upper() + ": " + str(layout["rest_source"]))
'''


def write():
    THRALL_PROBE.write_text(source())
