#!/usr/bin/env python3
"""Repaint only requested hidden pixels with rr-02 empirical visible-value fills."""
from __future__ import annotations
import json
from pathlib import Path
import sys
import numpy as np
from PIL import Image
CASE = Path(__file__).resolve().parent
sys.path.insert(0, str(CASE.parents[3] / 'tools'))
import maquette_cutout as mq
from cutout_pipeline.cases import CutoutError, read_json, write_json, digest


def value_reference(paint, owners, names, part, materials, policy, view):
    index = names.index(part)
    own = owners == index
    if int(own.sum()) >= mq.FILL_DEFAULTS['palette_min_own_pixels']:
        return own, {'rule': 'same_part', 'part': part}
    explicit = policy.get('sparse_overrides', {}).get(view + '/' + part)
    if explicit:
        reference_part = explicit['part']
        reference = owners == names.index(reference_part)
        if explicit['rule'] == 'matching_tones':
            yy, xx = np.nonzero(reference)
            sy, sx = np.nonzero(own)
            if not len(sx): raise CutoutError('Sparse matching tones need original material pixels')
            source_lab, candidate_lab = mq.to_lab(paint[own, :3]), mq.to_lab(paint[reference, :3])
            # Existing rr-02 minimum donor count. Material distance first,
            # spatial distance second, source y/x order for exact ties.
            material_distance = ((candidate_lab[:, None] - source_lab[None]) ** 2).sum(-1).min(-1)
            spatial_distance = ((yy[:, None] - sy[None]) ** 2 + (xx[:, None] - sx[None]) ** 2).min(-1)
            order = np.lexsort((xx, yy, spatial_distance, material_distance))
            count = mq.FILL_DEFAULTS['palette_min_own_pixels']
            if len(order) < count: raise CutoutError('Explicit sparse region is still too small')
            reference[:] = False
            reference[yy[order[:count]], xx[order[:count]]] = True
        elif explicit['rule'] != 'full_visible':
            raise CutoutError('Unknown explicit sparse reference rule')
        return reference, dict(explicit, source='Director explicit same-view sparse reference')
    candidates = [name for name in names if name != part and materials[name] == materials[part]
                  and int((owners == names.index(name)).sum()) >= mq.FILL_DEFAULTS['palette_min_own_pixels']]
    if not candidates:
        raise CutoutError('TODO_DESIGN_sparse_reference_' + view + '_' + part)
    yy, xx = np.nonzero(own)
    if not len(xx): raise CutoutError('Sparse part has no visible material/location reference')
    def distance(name):
        y, x = np.nonzero(owners == names.index(name))
        # Exact source pixel distance, deterministic label-order tie.
        return min(int(((yy - py) ** 2 + (xx - px) ** 2).min()) for py, px in zip(y, x))
    name = min(candidates, key=lambda n: (distance(n), names.index(n)))
    return owners == names.index(name), {'rule': 'same_view_same_material_nearest_part', 'part': name,
        'distance_squared_px': distance(name), 'material': materials[name]}


def match_values(result, hidden, reference_rgb):
    """Round 2's full visible distribution applies to every hidden pixel.

    rr-02's fixed outline override can dominate thin fills (15/16 wing pixels).
    Keep the source-derived spatial value order, but include those hidden edge
    pixels in empirical quantile assignment. No visible RGB/alpha changes.
    """
    count = int(hidden.sum())
    if not count: return result
    palette, _ = mq.part_palette(reference_rgb)
    reference_l = np.sort(mq.to_lab(reference_rgb)[:, 0])
    quantiles = (np.arange(count) + .5) / count
    targets = reference_l[np.minimum((quantiles * len(reference_l)).astype(int), len(reference_l) - 1)]
    order = np.argsort(mq.to_lab(result[hidden, :3])[:, 0], kind='stable')
    colors = palette[np.abs(targets[:, None] - mq.to_lab(palette)[None, :, 0]).argmin(axis=1)]
    positions = np.flatnonzero(hidden)
    result.reshape(-1, 4)[positions[order], :3] = colors
    return result


def preserve_manual_paint(root):
    """Accept only our previous generated bytes or a recorded fresh rebuild."""
    manifest = root / 'hidden_fills/index.json'
    if not manifest.is_file(): return
    previous = read_json(manifest)
    reset_path = root / 'proof/ownership_rebuild_manifest.json'
    reset = read_json(reset_path).get('outputs', {}) if reset_path.is_file() else {}
    for record in previous.get('requests', []):
        for output in record.get('outputs', []):
            path = root / output['output']
            if path.is_file() and digest(path) not in [output['output_sha256'], reset.get(output['output'])]:
                raise CutoutError('Preserve manually changed hidden paint: ' + output['output'])


def fill():
    preserve_manual_paint(CASE)
    config = read_json(CASE / 'cutout.json')
    recipe = read_json(CASE / 'recipes/rig.json')
    policy = read_json(CASE / 'recipes/value_reference.json')
    names = list(read_json(CASE / 'source/spec.json')['labels'])
    records, pending = [], []
    for view, layout_path in config['layouts'].items():
        paint = np.array(Image.open(CASE / f'source/{view}/processed.png').convert('RGBA'))
        owners = np.load(CASE / f'registered/{view}_owners.npy')
        layout = read_json(CASE / layout_path)
        for part in names:
            visible = owners == names.index(part)
            hidden = np.load(CASE / f'registered/{view}_hidden_{part}.npy')
            record = {'view': view, 'part': part, 'hidden_pixels': int(hidden.sum()),
                'own_visible_pixels': int(visible.sum()), 'visible_mask_sha256': mq.array_digest(visible),
                'hidden_mask_sha256': mq.array_digest(hidden)}
            if not hidden.any():
                result = np.zeros_like(paint); result[visible] = paint[visible]
                record.update(status='no_hidden_pixels', value_reference={'rule': 'not_applicable', 'reason': 'No retained hidden pixels'})
            else:
                try:
                    reference, rule = value_reference(paint, owners, names, part, recipe['materials'], policy, view)
                    rgb = paint[reference, :3]
                    result, metrics = mq.fill_pixels(paint, visible, hidden, paint[..., :3], reference,
                        'diffusion', palette_pixels=rgb, conditioning_visible=visible if rule['rule'] == 'same_part' else np.zeros_like(visible), value_pixels=rgb)
                    result = match_values(result, hidden, rgb)
                    metrics['value_scope'] = 'Complete hidden region including its edges; approved visible RGBA unchanged'
                    metrics['value_distribution'] = metrics['diffusion'].pop('value_distribution', {})
                    metrics['outline_tone'] = None
                    if hidden.any():
                        actual_l, reference_l = mq.to_lab(result[hidden, :3])[:, 0], mq.to_lab(rgb)[:, 0]
                        low, high = np.percentile(reference_l, [25, 75])
                        metrics['value_distribution'] = {'basis': 'Complete hidden region including edges, same-view visible reference',
                            'visible_median_l': float(np.median(reference_l)), 'hidden_median_l': float(np.median(actual_l)),
                            'median_difference_l': float(abs(np.median(actual_l) - np.median(reference_l))),
                            'visible_midtones_l': [float(low), float(high)],
                            'hidden_midtones_pixels': int(((actual_l >= low) & (actual_l <= high)).sum())}
                    record.update(metrics, status='filled', value_reference=dict(rule, view=view,
                        pixels=int(reference.sum()), mask_sha256=mq.array_digest(reference), rgb_sha256=mq.array_digest(rgb)))
                except CutoutError as error:
                    if not str(error).startswith('TODO_DESIGN_sparse_reference_'): raise
                    pending.append(str(error))
                    record.update(status='pending_design', reason=str(error))
                    result = np.zeros_like(paint); result[visible] = paint[visible]; result[hidden] = mq.MAGENTA
            outputs = []
            covered = np.zeros_like(hidden)
            for node in layout['parts']:
                if not node.get('hidden_material') or node['logical_part'] != part: continue
                path = CASE / node['file']
                before = np.array(Image.open(path).convert('RGBA'))
                x, y = node['offset']; h, w = before.shape[:2]
                mask = before[..., 3] > 128
                if np.any(mask & ~hidden[y:y+h, x:x+w]): raise CutoutError('Runtime alpha differs from repaired request')
                covered[y:y+h, x:x+w] |= mask
                before[mask] = result[y:y+h, x:x+w][mask]
                mq.save_image(path, Image.fromarray(before))
                outputs.append({'output': node['file'], 'output_sha256': digest(path), 'alpha_sha256': mq.array_digest(before[..., 3])})
            if not np.array_equal(covered, hidden): raise CutoutError('Incomplete hidden runtime coverage')
            record['outputs'] = outputs
            preview = np.full_like(paint, mq.GREEN); preview[visible | hidden] = result[visible | hidden]
            path = CASE / f'hidden_fills/{view}_{part}.png'
            mq.save_image(path, Image.fromarray(preview))
            record.update(preview=str(path.relative_to(CASE)), preview_sha256=digest(path))
            records.append(record)
    mq.contact_sheet([(r['view'] + '/' + r['part'] + '\n' + r['status'], Image.open(CASE / r['preview']).convert('RGBA')) for r in records], CASE / 'hidden_fills/contact_sheet.png')
    # Bind every geometric/visible authority, excluding refreshable exposure sheets.
    protected = {p for folder in ['source', 'registered', 'segmented', 'layouts'] for p in (CASE / folder).rglob('*') if p.is_file() and p.suffix != '.import'}
    protected |= set((CASE / 'hidden_requests').glob('*.png')) - {CASE / 'hidden_requests/contact_sheet.png'}
    protected |= {CASE / 'recipes/rig.json', CASE / 'recipes/ownership_repair.json', CASE / 'recipes/value_reference.json'}
    manifest = {'schema_version': 1, 'complete': not pending, 'pending_design': pending, 'method': 'diffusion',
        'parameters': mq.FILL_DEFAULTS, 'implementation_sha256': digest(Path(__file__)),
        'rr02_implementation_sha256': digest(Path(mq.__file__)),
        'protected_inputs': {str(p.relative_to(CASE)): digest(p) for p in sorted(protected)}, 'requests': records}
    write_json(CASE / 'hidden_fills/index.json', manifest)
    write_json(CASE / 'recipes/hidden_fill.json', dict(policy, method='diffusion', parameters=mq.FILL_DEFAULTS))
    config['hidden_fill'] = {'recipe': 'recipes/hidden_fill.json', 'manifest': 'hidden_fills/index.json', 'pending_design': pending}
    config['source_baseline']['art_status'] = 'hidden_material_incomplete' if pending else 'hidden_filled_pending_director_review'
    write_json(CASE / 'cutout.json', config)
    report = {'ok': not pending, 'requests': len(records), 'pending_design': pending, 'rest_identity': mq.rest_identity(CASE)}
    write_json(CASE / 'proof/hidden_fill_report.json', report)
    return report

if __name__ == '__main__':
    report = fill(); print(json.dumps(report, indent=2)); sys.exit(0 if report['ok'] else 1)
